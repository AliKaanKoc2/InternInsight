class Organization {
  final String name;
  final String type;
  final String industry;
  final String city;
  final String logoUrl;
  final double rating;
  final int experienceCount;

  const Organization({
    required this.name,
    required this.type,
    required this.industry,
    required this.city,
    required this.logoUrl,
    required this.rating,
    required this.experienceCount,
  });
}
